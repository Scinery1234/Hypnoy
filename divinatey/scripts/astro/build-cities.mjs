// Generates src/core/cities.js from GeoNames (via the all-the-cities and
// cities.json npm packages) with each city's IANA timezone looked up from
// timezone-boundary-builder polygons (geo-tz). Run: node scripts/astro/build-cities.mjs [minPopulation]
// (needs: npm i --no-save all-the-cities@3.1.0 cities.json@1.1.65 geo-tz@8.1.10)
import {createRequire} from 'node:module';import fs from 'node:fs';
const require=createRequire(import.meta.url);
const cities=require('all-the-cities');
const admin1=require('cities.json/admin1.json');
const {find}=require('geo-tz');
const MIN=+(process.argv[2]||1000);
const region=new Intl.DisplayNames(['en'],{type:'region'});
const adminName=Object.fromEntries(admin1.map(a=>[a.code,a.name]));
const country=cc=>{try{return region.of(cc)}catch(e){return cc}};

const rows=cities.filter(c=>c.population>=MIN).sort((a,b)=>b.population-a.population);
const tzs=[],tzIdx=new Map(),places=[],placeIdx=new Map(),seen=new Set(),out=[];
const idx=(arr,map,v)=>{if(!map.has(v)){map.set(v,arr.length);arr.push(v);}return map.get(v);};
for(const c of rows){
  const[lon,lat]=c.loc.coordinates;
  const adm=adminName[`${c.country}.${c.adminCode}`]||'';
  const place=[adm,country(c.country)].filter(Boolean).join(', ');
  const key=c.name+'|'+place;
  if(seen.has(key))continue;seen.add(key);
  const tz=find(lat,lon)[0];
  if(!tz)continue;
  out.push([c.name.replace(/[|\n]/g,' '),idx(places,placeIdx,place),lat.toFixed(2),lon.toFixed(2),idx(tzs,tzIdx,tz)].join('|'));
}
const js=`// ─── Generated by tools/build-cities.mjs — do not edit by hand ───────────────
// ${out.length} places with population ≥ ${MIN}, largest first.
// City data: GeoNames (geonames.org), CC BY 4.0. Timezones: timezone-boundary-builder via geo-tz.
// Row: name|placeIndex|lat|lon|tzIndex
const CITY_TZ=${JSON.stringify(tzs)};
const CITY_PLACE=${JSON.stringify(places)};
const CITY_ROWS=${JSON.stringify(out.join('\n'))};
`;
fs.writeFileSync(new URL('../../shared/astro/core/cities.js',import.meta.url),js);
console.log(out.length,'cities',(js.length/1024/1024).toFixed(2)+' MB');
